def get_fetus_week(week: int) -> dict:
    """يرجع بيانات الجنين لأقرب أسبوع متاح"""
    available = sorted(FETUS_DATA.keys())
    closest = min(available, key=lambda w: abs(w - week))
    data = FETUS_DATA[closest].copy()
    data["requested_week"] = week
    data["shown_week"] = closest
    return data
